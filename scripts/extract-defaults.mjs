// Generates api/_defaults.js from the DEFAULT_* constants in procable-data.js.
// The server uses it when the admin never saved a section (products, cables...) so prices are verified
// against exactly what visitors see. Run after editing defaults:  node scripts/extract-defaults.mjs
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(root, 'public', 'procable-data.js'), 'utf8');
const cut = src.indexOf('const ProCable = {');
if (cut < 0) throw new Error('const ProCable not found');
const ctx = vm.createContext({ localStorage: {}, document: {}, window: {}, navigator: {} });
vm.runInContext(src.slice(0, cut), ctx);
const out = JSON.parse(vm.runInContext(`JSON.stringify({
  categories: DEFAULT_CATEGORIES, products: DEFAULT_PRODUCTS, connectors: DEFAULT_CONNECTORS, cables: DEFAULT_CABLES,
  shipping: DEFAULT_SHIPPING, settings: DEFAULT_SETTINGS,
  coupons: [{ code: "ATTRACTIVE10", type: "percent", value: 10, active: true }]
})`, ctx));
delete out.settings.adminPassHash;
fs.writeFileSync(path.join(root, 'api', '_defaults.js'), '// AUTO-GENERATED by scripts/extract-defaults.mjs. Do not edit by hand.\nexport default ' + JSON.stringify(out) + ';\n');
console.log('products', out.products.length, '| connectors', out.connectors.length, '| cables', out.cables.length, '| shipping', out.shipping.length);
